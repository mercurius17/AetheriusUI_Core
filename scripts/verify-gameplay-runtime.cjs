'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { EventEmitter } = require('node:events');
const testRoot = path.resolve(process.argv[2] || 'C:/Code/Aetherius-MP-Teste');
const runtime = path.join(testRoot, 'runtime');
const esbuild = require(path.join(testRoot, 'repos', 'aetherius-server', 'server', 'node_modules', 'esbuild'));
const systemFile = path.join(runtime, 'core-system.cjs');
esbuild.buildSync({ entryPoints: [path.join(testRoot, 'repos', 'aetherius-server', 'server', 'ts', 'systems', 'aetheriusUiSystem.ts')], bundle: true, platform: 'node', format: 'cjs', outfile: systemFile });
process.chdir(runtime);
async function main() {
  const { ScampServer } = require(path.join(runtime, 'scam_native.node'));
  const settings = JSON.parse(fs.readFileSync('server-settings.json', 'utf8'));
  settings.port = 17779;
  settings.databaseDriver = 'file';
  settings.databaseName = 'gameplay-validation-world';
  settings.papyrusScriptAllowlist = [];
  const host = new ScampServer(JSON.stringify(settings)); host._setSelf(host); host.attachSaveStorage();
  const { AetheriusUiSystem } = require(systemFile);
  const system = new AetheriusUiSystem(), gm = new EventEmitter(), sent = [];
  const instrumented = {};
  for (const name of ['get', 'set', 'makeProperty', 'getServerSettings', 'getUserActor', 'isConnected', 'lookupEspmRecordById']) instrumented[name] = host[name].bind(host);
  const ctx = { svr: instrumented, gm };
  const nativeSend = host.sendCustomPacket.bind(host);
  instrumented.sendCustomPacket = (user, json) => { sent.push({ user, ...JSON.parse(json) }); nativeSend(user, json); };
  host.on('connect', user => system.connect(user));
  host.on('disconnect', user => system.disconnect(user));
  host.on('customPacket', (user, json) => { const content = JSON.parse(json); system.customPacket(user, content.customPacketType, content, ctx); });
  await system.initAsync(ctx);
  const bot = host.createBot(); host.tick();
  const userId = bot.getUserId();
  assert.equal(host.isConnected(userId), true);
  const actor = host.createActor(0, [-66260.9, 94442.18, -13655.73], 207.69, 0x3c, 900099);
  host.setUserActor(userId, actor); gm.emit('spawnAllowed', userId);
  const sessionId = sent.find(packet => packet.sessionId)?.sessionId;
  assert.ok(sessionId);
  const request = { protocolVersion: 1, kind: 'request', messageId: 'native-test-1', correlationId: 'native-test-c1', sessionId, moduleId: 'class', action: 'snapshot', payload: {} };
  const send = async envelope => { bot.send({ t: 1, contentJsonDump: JSON.stringify({ customPacketType: 'aetherius-ui:v1:request', envelope }) }); host.tick(); await new Promise(resolve => setImmediate(resolve)); host.tick(); };
  await send(request);
  const response = sent.find(packet => packet.envelope?.correlationId === request.correlationId);
  assert.equal(response?.envelope?.kind, 'response');
  assert.equal(response.envelope.payload.player.playerId, actor);
  assert.ok(response.envelope.payload.readOnlyReason);
  assert.equal(JSON.parse(host.get(actor, 'playerClassData')).playerId, actor);
  await send({ ...request, messageId: 'native-test-2', correlationId: 'native-test-c2', payload: { actorId: actor + 1 } });
  assert.equal(sent.find(packet => packet.envelope?.correlationId === 'native-test-c2')?.envelope?.kind, 'error');
  await send({ ...request, messageId: 'native-test-3', correlationId: 'native-test-c3', action: 'selectClass', payload: { classId: 'guardiao' } });
  assert.equal(sent.find(packet => packet.envelope?.correlationId === 'native-test-c3')?.envelope?.payload.result.success, false);
  assert.equal(JSON.parse(host.get(actor, 'playerClassData')).classId, null);
  await send(request);
  assert.equal(sent.filter(packet => packet.envelope?.correlationId === request.correlationId).length, 2);
  const before = sent.length;
  await send({ ...request, messageId: 'stale-message', sessionId: 'stale-session' });
  assert.equal(sent.length, before);
  await system.updateAsync(ctx);
  const hud = sent.find(packet => packet.envelope?.moduleId === 'hud');
  assert.equal(hud, undefined, 'TrueHUD must retain exclusive ownership of vital bars');
  const query = async (moduleId, action, payload = {}) => {
    const correlationId = 'read-' + sent.length;
    await send({ ...request, messageId: correlationId, correlationId, moduleId, action, payload });
    return sent.find(packet => packet.envelope?.correlationId === correlationId)?.envelope;
  };
  // Reproduce the real player's mixed inventory on an isolated validation actor.
  // Never rewrite the player's inventory or use its untrusted equipmentDump.
  const savedPlayer = fs.readdirSync(path.join(runtime, 'world/changeForms')).map(name => JSON.parse(fs.readFileSync(path.join(runtime, 'world/changeForms', name), 'utf8'))).find(row => row.profileId === 900001);
  assert.ok(savedPlayer?.inv?.entries.length, 'Real local player inventory required for regression');
  host.set(actor, 'inventory', savedPlayer.inv);
  const mixed = await query('inventory', 'snapshot');
  assert.equal(mixed.kind, 'response', 'Mixed armor/gold inventory must produce a valid protocol response');
  assert.equal(mixed.payload.items.length, savedPlayer.inv.entries.length);
  assert.equal(mixed.payload.summary.gold, savedPlayer.inv.entries.filter(row => row.baseId === 15).reduce((sum, row) => sum + row.count, 0));
  assert.ok(mixed.payload.items.some(row => row.category === 'apparel' && !Object.hasOwn(row, 'damage')));
  assert.deepEqual(host.get(actor, 'inventory'), savedPlayer.inv, 'Read projection must preserve authoritative inventory');
  const armor = mixed.payload.items.find(row => row.category === 'apparel');
  const armorDetail = await query('inventory', 'itemDetails', { itemId: armor.id, expectedRevision: mixed.payload.revision });
  assert.equal(armorDetail.kind, 'response');
  assert.equal(armorDetail.payload.previewToken, 'native-preview:' + armor.key);
  host.set(actor, 'inventory', { entries: [{ baseId: 0x12eb7, count: 2 }] });
  const inv = await query('inventory', 'snapshot');
  assert.equal(inv.kind, 'response');
  assert.equal(inv.payload.items[0].count, 2);
  assert.equal(inv.payload.items[0].category, 'weapons');
  assert.deepEqual(inv.payload.items[0].actions, []);
  assert.ok(inv.payload.readOnlyReason);
  const detail = await query('inventory', 'itemDetails', { itemId: inv.payload.items[0].id, expectedRevision: inv.payload.revision });
  assert.equal(detail.payload.item.name, inv.payload.items[0].name);
  assert.equal(detail.payload.previewToken, 'native-preview:12eb7');
  assert.equal((await query('inventory', 'itemDetails', { itemId: 'foreign', expectedRevision: inv.payload.revision })).kind, 'error');
  assert.equal((await query('inventory', 'equip', { itemId: inv.payload.items[0].id })).kind, 'error');
  assert.equal((await query('inventory', 'snapshot', { actorId: actor + 1 })).kind, 'error');
  const spells = await query('spells', 'snapshot');
  assert.equal(spells.kind, 'response');
  assert.equal(spells.payload.summary.known, host.get(actor, 'knownSpells').length);
  assert.throws(() => host.set(actor, 'knownSpells', []));
  bot.destroy(); host.tick(); host.destroyActor(actor);
  const evidence = { at: new Date().toISOString(), plugins: host.getEspmLoadOrder().length, nativeMockTransport: true, boundActor: true, persistenceReadWrite: true, payloadIdentityRejected: true, unavailableMutationsClosed: true, staleSessionRejected: true, duplicateResponse: true, trueHudExclusive: true, inventoryNativeRead: true, spellsNativeRead: true, inGameClient: false };
  fs.writeFileSync('gameplay-runtime-validation.json', JSON.stringify(evidence, null, 2) + '\n');
  console.log(JSON.stringify(evidence));
}
main().then(() => process.exit(0), error => { console.error(error); process.exit(1); });
