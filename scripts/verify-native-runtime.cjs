'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(process.argv[2] || 'C:/Code/Aetherius-MP-Teste/runtime');
process.chdir(root);
const manifest = JSON.parse(fs.readFileSync('data/aetherius-loadorder.json', 'utf8'));
const settings = JSON.parse(fs.readFileSync('server-settings.json', 'utf8'));
settings.port = 17778;
settings.databaseDriver = 'file';
settings.databaseName = 'native-validation-world';
const { ScampServer } = require(path.join(root, 'scam_native.node'));
const host = new ScampServer(JSON.stringify(settings));
host._setSelf(host);
const opened = host.getEspmLoadOrder();
assert.deepEqual(opened.map(n => path.basename(n).toLowerCase()), manifest.loadOrder.map(n => n.toLowerCase()));
const methods = ['get', 'set', 'makeProperty', 'getServerSettings', 'getEspmLoadOrder', 'getUserActor', 'isConnected'];
for (const name of methods) assert.equal(typeof host[name], 'function', name);
host.attachSaveStorage();
for (let i = 0; i < 3; i++) host.tick();
const evidence = { at: new Date().toISOString(), node: process.version, openedPlugins: opened.length, loadOrderMatch: true, methods, combatApi: typeof host.applyActorCombatProfile === 'function' };
fs.writeFileSync('native-runtime-validation.json', JSON.stringify(evidence, null, 2) + '\n');
console.log(JSON.stringify(evidence));
process.exit(0);
