'use strict';
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const root=path.resolve(__dirname,'..'),core=require('./core-path.cjs');
const esbuild=require(path.join(core,'referencias','repositories','aetherius-server','server','node_modules','esbuild'));
const local=path.join(root,'.local');fs.mkdirSync(local,{recursive:true});
require('./core-overlay.cjs');
esbuild.buildSync({entryPoints:[path.join(core,'tests','core.test.ts')],bundle:true,platform:'node',format:'cjs',target:'node18',outfile:path.join(local,'core.test.cjs')});
cp.execFileSync(process.execPath,['--test',path.join(local,'core.test.cjs')],{stdio:'inherit',cwd:core});
const staged=path.join(local,'core-overlay');
for(const folder of ['shared','sdk'])fs.cpSync(path.join(core,folder),path.join(staged,folder),{recursive:true});
const nested=path.join(staged,'referencias','repositories','aetherius-server','server','ts','systems');fs.mkdirSync(nested,{recursive:true});
fs.copyFileSync(path.join(root,'integrations','overlays','aetherius-server','server','ts','systems','aetheriusUiSystem.ts'),path.join(nested,'aetheriusUiSystem.ts'));
fs.copyFileSync(path.join(core,'referencias','repositories','aetherius-server','server','ts','systems','system.ts'),path.join(nested,'system.ts'));
esbuild.buildSync({entryPoints:[path.join(nested,'aetheriusUiSystem.ts')],bundle:true,platform:'node',format:'cjs',target:'node18',outfile:path.join(local,'core-system.cjs')});
console.log('Core suite and public-registration overlay bundled successfully.');
const frontend=path.join(core,'frontend','Data','MeridianUI','aetheriusui');
new (require('node:vm').Script)(require('./frontend-overlay.cjs').overlay(frontend));
console.log('Frontend subroute overlay anchors verified and JavaScript parsed.');
require('./client-regression.cjs');
